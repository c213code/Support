// Похожесть двух коротких текстов по пересечению слов (коэффициент
// Жаккара). Нужна, чтобы предложить "похоже на этот тикет — приклеить?"
// когда один и тот же запрос прилетает по нескольку раз ("доступ беру",
// "ДТ ашылмайды").
//
// Намеренно тупой алгоритм без ИИ: считается мгновенно на клиенте, ничего
// не стоит и, главное, ничего не решает сам — только подсказывает, а
// объединяет всегда человек.

// Слова, которые есть почти в каждом обращении и поэтому только раздувают
// совпадение: если их не выкинуть, "не могу зайти" и "не могу открыть"
// выглядят как одно и то же.
const STOP_WORDS = new Set([
  "не", "и", "в", "на", "с", "по", "у", "а", "но", "же", "ли", "что", "это",
  "как", "для", "мне", "меня", "мы", "нам", "он", "она", "они", "есть",
  "бар", "жоқ", "жок", "бір", "бир", "мен", "біз", "биз", "ол", "деп",
  "керек", "пожалуйста", "помогите", "көмектесіңіз", "көмектесіңізші",
]);

function tokenize(text: string): Set<string> {
  return new Set(
    text
      .toLowerCase()
      // Цифры оставляем: "3 балл", "404" — как раз то, что различает
      // похожие обращения.
      .replace(/[^\p{L}\p{N}\s]/gu, " ")
      .split(/\s+/)
      .filter((w) => w.length > 2 && !STOP_WORDS.has(w))
  );
}

export function similarity(a: string, b: string): number {
  const tokensA = tokenize(a);
  const tokensB = tokenize(b);
  if (tokensA.size === 0 || tokensB.size === 0) return 0;

  let shared = 0;
  for (const token of tokensA) {
    if (tokensB.has(token)) shared++;
  }
  return shared / (tokensA.size + tokensB.size - shared);
}

// Порог, с которого показываем подсказку. Подобран так, чтобы ловить
// повторы одного запроса, но не предлагать склеить любые два обращения
// про вход в аккаунт.
export const SIMILARITY_HINT_THRESHOLD = 0.34;

// Длина «основы» слова для сравнения переформулировок. Казахский —
// агглютинативный: "оқушы" / "оқушының" / "оқушыда" — одно и то же слово с
// разными окончаниями, и различаются они только хвостом. Пять символов
// отсекают хвост, оставляя корень.
const STEM_LENGTH = 5;

function stems(text: string): Set<string> {
  return new Set(
    text
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s]/gu, " ")
      .split(/\s+/)
      .filter(Boolean)
      .map((word) => word.slice(0, STEM_LENGTH))
  );
}

// Отличается ли переформулировка от исходника только косметикой —
// окончаниями, регистром, пунктуацией.
//
// Нужно, чтобы "ИИ предлагает описание точнее" не дёргало агента ради
// правок вроде "Оқушы құпия сөзі керек" → "Оқушының құпия сөзі керек":
// грамматика причёсана, смысл тот же, а решение принимать всё равно
// человеку. Смысл проверки в том, что состав слов не изменился: ничего не
// убрано (приветствие, почта, цитата) и ничего не добавлено.
export function isCosmeticRewrite(before: string, after: string): boolean {
  const a = stems(before);
  const b = stems(after);

  // Всё, что есть только в одной из версий. Если пусто — версии совпали с
  // точностью до окончаний.
  const onlyIn = [...a].filter((s) => !b.has(s)).concat([...b].filter((s) => !a.has(s)));

  // Различие из коротких слов без цифр — тоже косметика: так модель
  // разбивает одну форму на две ("шықпайды" → "шықпай тұр") или добавляет
  // служебное слово. А вот цифры информативны всегда: "ошибка 404" — это
  // содержание, даже если само число короткое.
  return onlyIn.every((stem) => stem.length < 4 && !/\d/.test(stem));
}
