// Похожесть двух коротких текстов по пересечению слов (коэффициент
// Жаккара). Нужна, чтобы предложить "похоже на этот тикет — приклеить?"
// когда один и тот же запрос прилетает по нескольку раз ("доступ беру",
// "ДТ ашылмайды").
//
// Намеренно тупой алгоритм без ИИ: считается мгновенно на клиенте, ничего
// не стоит и, главное, ничего не решает сам — только подсказывает, а
// объединяет всегда человек.

// Слова, которые есть почти в каждом обращении и поэтому только раздувают
// совпадение: если их не выкинуть, "не могу зайти" и "не могу открыть"
// выглядят как одно и то же.
const STOP_WORDS = new Set([
  "не", "и", "в", "на", "с", "по", "у", "а", "но", "же", "ли", "что", "это",
  "как", "для", "мне", "меня", "мы", "нам", "он", "она", "они", "есть",
  "бар", "жоқ", "жок", "бір", "бир", "мен", "біз", "биз", "ол", "деп",
  "керек", "пожалуйста", "помогите", "көмектесіңіз", "көмектесіңізші",
]);

function tokenize(text: string): Set<string> {
  return new Set(
    text
      .toLowerCase()
      // Цифры оставляем: "3 балл", "404" — как раз то, что различает
      // похожие обращения.
      .replace(/[^\p{L}\p{N}\s]/gu, " ")
      .split(/\s+/)
      .filter((w) => w.length > 2 && !STOP_WORDS.has(w))
  );
}

export function similarity(a: string, b: string): number {
  const tokensA = tokenize(a);
  const tokensB = tokenize(b);
  if (tokensA.size === 0 || tokensB.size === 0) return 0;

  let shared = 0;
  for (const token of tokensA) {
    if (tokensB.has(token)) shared++;
  }
  return shared / (tokensA.size + tokensB.size - shared);
}

