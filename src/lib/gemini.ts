export async function rewriteTicketDescriptionWithAI(
  raw: string
): Promise<string | null> {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey || !raw.trim()) return null;

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), GEMINI_TIMEOUT_MS);

  try {
    const res = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/${GEMINI_MODEL}:generateContent?key=${apiKey}`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        signal: controller.signal,
        body: JSON.stringify({
          systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
          contents: [
            ...FEW_SHOT_TURNS.flatMap(({ user, model }) => [
              { role: "user", parts: [{ text: user }] },
              { role: "model", parts: [{ text: model }] },
            ]),
            { role: "user", parts: [{ text: raw }] },
          ],
          generationConfig: { temperature: 0.15, maxOutputTokens: 150 },
        }),
      }
    );

    if (!res.ok) return null;

    const data = await res.json();
    const text: unknown = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    return typeof text === "string" && text.trim() ? text.trim() : null;
  } catch {
    // Таймаут, сеть, невалидный ответ — не наша забота здесь, вызывающий
    // код откатится на regex-чистку.
    return null;
  } finally {
    clearTimeout(timeout);
  }
}
