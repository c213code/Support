import type { IssueStatus } from "@/lib/status";

// Распознаёт по собственной реплике агента в группе, что он сделал с
// обращением, — чтобы статус проставлялся сам, а вечерний разбор из
// основной работы превращался в проверку.
//
// Правилами, а не ИИ: на разборе реальной недельной переписки (91 реплика)
// эти же признаки уверенно опознали половину ответов, а стоят они ноль и
// не зависят от доступности внешнего сервиса. Что не опознали — просто
// оставляем человеку, это не ошибка.
//
// Порядок проверок важен: "жөңделді, әріптестерім қарады" — это про
// сделано, а не про передано, поэтому готовность проверяется первой.

// Сделано. Слова взяты не на глаз: в выгрузке четырёх групп они дают весь
// хвост реплик о готовности, и порядок частот такой —
//   ауыстырылды 469, жіберілді 408, қосылды 200, шешілді 199, ашылды 150,
//   жөнделді 114, өзгертілді 101, өшірілді 97, дұрысталды 69, түзелді 38.
//
// Первая версия знала пять из них, и три самых заметных пропускала.
// "жіберілді" не ловилось даже через "берілді": перед ним стоит буква, а
// граница слова требует её отсутствия — то есть самая частая связка
// корпуса ("ауыстырылды, жіберілді", 166 раз) опознавалась только по
// первому слову, а одиночное "жіберілді" не опознавалось вовсе.
//
// Осторожно с будущим временем: "бүгін шешіледі" — это обещание, а не
// факт, поэтому "шешіледі"/"жөнделеді" из совпадения исключены.
const DONE =
  /(?<![\p{L}])(жөнделді|жөңделді|жөндедік|жөңдедік|шешілді|шештік|өзгертілді|өзгерттік|ауыстырылды|ауыстырдық|қосылды|қостық|берілді|бердік|жіберілді|жібердік|ашылды|аштық|өшірілді|өшірдік|түзелді|түзедік|дұрысталды|дұрыстадық|жасалды|жасадық)(?![\p{L}])/iu;

// Передано коллегам: "әріптестеріме жібердім", "командаға айттық",
// "әріптестерім қарап жатыр".
const ESCALATED =
  /(әріптес|команда)\w*.{0,30}(жібер|айт|бер|қара)|(жібер|айт)\w*.{0,20}(әріптес|команда)/iu;

// Взято в работу: "жақсы, қарап береміз", "тексеріп көреміз", "қазір
// қараймын". Самая широкая категория, поэтому проверяется последней.
const IN_PROGRESS =
  /(қарап бер|қарап көр|қарап жатыр|қараймын|қарайм|қарайық|тексер|көрейін|көреміз|қабылда)/iu;

export type AgentIntent = {
  status: IssueStatus;
  // Требует ли перевод подтверждения человеком. "Решено" уходит в репорт
  // боссам, поэтому его не ставим молча — спрашиваем и заодно просим
  // нормальную заметку: само "жөңделді" в отчёте ничего не объясняет.
  needsConfirmation: boolean;
};

export function detectAgentIntent(text: string): AgentIntent | null {
  const trimmed = text.trim();
  if (!trimmed) return null;

  if (DONE.test(trimmed)) {
    return { status: "RESOLVED", needsConfirmation: true };
  }
  if (ESCALATED.test(trimmed)) {
    return { status: "ESCALATED", needsConfirmation: false };
  }
  if (IN_PROGRESS.test(trimmed)) {
    return { status: "IN_PROGRESS", needsConfirmation: false };
  }
  return null;
}
