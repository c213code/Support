export type ModelFamily = "gpt-oss" | "deepseek" | "glm" | "mimo" | "qwen" | "other";

export function modelFamily(model: string): ModelFamily {
  const id = model.toLowerCase();
  if (id.includes("gpt-oss")) return "gpt-oss";
  if (id.includes("deepseek")) return "deepseek";
  if (id.includes("glm")) return "glm";
  if (id.includes("mimo")) return "mimo";
  if (id.includes("qwen")) return "qwen";
  return "other";
}

// Напоминание о формате в конце сообщения пользователя — для моделей, которые
// с включёнными рассуждениями иногда начинают ответ не с JSON.
const FORMAT_REMINDER =
  "\n\nОтветь только JSON-объектом {\"status\": ..., \"note\": ..., \"evidence\": ..., \"reason\": ...} — без текста до и после.";

// Правила вместо RECONCILE_RULES — только для прогона на истории
// (scripts/eval-reconcile.ts --rules=файл): так вариант промпта сравнивают
// с текущим, не трогая то, чем разбирает прод.
let rulesOverride: string | null = null;
export function overrideReconcileRules(rules: string | null): void {
  rulesOverride = rules;
}

// glossary — термины словаря компании, встретившиеся в тексте запроса
// (buildAiContext): «ДТ», «АА», «кинескоп» и т. п. Модель их не знает, а
// итог по переписке без них не понять («кинескопта жаңа вд ашу»).
export function buildReconcileMessages(
  model: string,
  userText: string,
  glossary = "",
  today = new Date().toISOString().slice(0, 10)
): Array<{ role: "system" | "user"; content: string }> {
  const family = modelFamily(model);
  const rules = (rulesOverride ?? RECONCILE_RULES) + glossary;
  const system =
    family === "mimo"
      ? `You are MiMo, an AI assistant developed by Xiaomi. Today's date: ${today}.\n\n${rules}`
      : rules;
  const user = family === "deepseek" || family === "qwen" ? userText + FORMAT_REMINDER : userText;
  return [
    { role: "system", content: system },
    { role: "user", content: user },
  ];
}

// Глубина рассуждений в теле запроса. У Groq — reasoning_effort (для
// gpt-oss: low / medium / high); у OpenRouter — единый reasoning.effort,
// который он сам переводит в параметр конкретной модели. temperature не
// трогаем: GLM, MiMo и DeepSeek в режиме рассуждений просят оставить 1.0
// (у DeepSeek она там вообще не действует).
export function reasoningParams(
  provider: "groq" | "openrouter",
  model: string
): Record<string, unknown> {
  const effort = process.env.RECONCILE_EFFORT?.trim() || defaultEffort(modelFamily(model));
  if (!effort) return {};
  return provider === "groq" ? { reasoning_effort: effort } : { reasoning: { effort } };
}

function defaultEffort(family: ModelFamily): string | null {
  switch (family) {
    // Классификация одного тикета — задача на внимательность, а не на
    // длинную цепочку: high уже с запасом, max у GLM/DeepSeek только дороже.
    case "gpt-oss":
    case "deepseek":
    case "glm":
      return "high";
    default:
      return null;
  }
}
