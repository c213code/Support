// переписывание через Groq — включается тоглом aiCleaningEnabled (см.
// lib/settings.ts). В отличие от регулярок ИИ понимает контекст, а не
// просто вырезает паттерны, поэтому лучше держит смысл сообщения. Groq
// выбран вместо Gemini из-за бесплатного tier без привязки карты (у
// Gemini free-tier квота равна 0, пока не подключишь биллинг).
//
// Вызывается из вебхука Telegram, который должен ответить быстро — при
// любой ошибке/таймауте/отсутствии ключа возвращаем null, и вызывающий код
// молча откатывается на cleanTicketDescription, а не роняет обработку
// сообщения.
const GROQ_MODEL = process.env.GROQ_MODEL || "llama-3.3-70b-versatile";
const GROQ_TIMEOUT_MS = 8000;

// Ответ модели, означающий "в сообщении нет запроса, тикет заводить не
// нужно" (см. хвост SYSTEM_PROMPT). Отдельное слово, а не пустая строка:
// пустой ответ неотличим от сбоя, а сбой должен приводить к откату на
// regex-чистку, а не к молчаливой потере сообщения.
export const AI_SKIP = "SKIP";

export function isAiSkip(text: string): boolean {
  return text.trim().replace(/[.!]*$/, "").toUpperCase() === AI_SKIP;
}

// Голых правил недостаточно — модель норовит съехать в вежливый пересказ
// ("Ученик сообщает, что не может войти в личный кабинет..."). Реальные
// агенты пишут описание как заголовок, в 3-10 слов, без подлежащего и
// сказуемого. Чтобы модель попадала в этот стиль, а не просто "понимала"
// правило текстом, стиль задаётся через few-shot: примеры идут отдельными
// сообщениями user/assistant в истории диалога (см. FEW_SHOT_TURNS ниже), а
// не одним текстовым блоком — так модель воспринимает их как прецедент "я
// уже так отвечал", а не как описание требования.
const SYSTEM_PROMPT = `Ты — часть тикет-системы поддержки онлайн-школы. Твоя единственная задача — сжать сырое сообщение ученика/родителя из Telegram в поле "Описание проблемы" тикета, ровно в том стиле, в котором это делает дежурный агент поддержки.

Стиль агента: короткая фраза по существу, обычно 3-10 слов, без вводных ("проблема в том, что", "ученик пишет", "жалуется на"), без вежливых оборотов, часто без явного сказуемого — как заголовок, а не пересказ.

Обязательно убирай: приветствия/прощания/благодарности/извинения за беспокойство, ссылки, email, номера телефонов, сами значения логина и пароля (что проблема именно в них — упоминай, но не значения), имена и подписи агентов, плейсхолдеры вложений вроде [Фото]/[Видео]/[Файл: ...].

Обязательно сохраняй: язык оригинала как есть (казахский/русский/смешанный — не переводи), конкретику по делу (какой кабинет/урок/предмет/класс, код ошибки, имя и класс ученика, если названы).

Ничего не придумывай и не добавляй сверх того, что было в сообщении.

Иногда сообщение начинается со строки вида "↩️ Имя: текст" — это цитата чужого сообщения, на которое отвечали (Telegram Reply), она идёт первой строкой, а сам ответ — после неё. Используй цитату только как контекст, чтобы понять, о чём вообще речь (без неё "дейді"/"солай" ничего не значит) — но в ответе саму цитату не повторяй и строку "↩️ ..." не копируй, пиши как обычно: суть проблемы одной фразой.

Ответ — только сама фраза описания: без кавычек, без markdown, без точки в конце, если это не полноценное предложение.

Если сообщение и так уже короткое и по делу — верни как есть.

ОСОБЫЙ СЛУЧАЙ: если в сообщении вообще нет запроса или проблемы — это просто приветствие ("Қайырлы күн", "Здравствуйте"), только ссылка или файл без пояснения, благодарность/подтверждение ("рахмет", "ок", "жарайды") или болтовня не по делу — ответь ровно одним словом: SKIP. Ничего больше не пиши. По таким сообщениям тикет заводить не нужно.`;

