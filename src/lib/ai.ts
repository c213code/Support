export async function rewriteTicketDescriptionWithAI(
  raw: string
): Promise<string | null> {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey || !raw.trim()) return null;

  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), GROQ_TIMEOUT_MS);

  try {
    const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`,
      },
      signal: controller.signal,
      body: JSON.stringify({
        model: GROQ_MODEL,
        temperature: 0.15,
        max_tokens: 150,
        messages: [
          { role: "system", content: SYSTEM_PROMPT },
          ...FEW_SHOT_TURNS.flatMap(({ user, assistant }) => [
            { role: "user", content: user },
            { role: "assistant", content: assistant },
          ]),
          { role: "user", content: raw },
        ],
      }),
    });

    if (!res.ok) return null;

    const data = await res.json();
    const text: unknown = data?.choices?.[0]?.message?.content;
    return typeof text === "string" && text.trim() ? text.trim() : null;
  } catch {
    // Таймаут, сеть, невалидный ответ — не наша забота здесь, вызывающий
    // код откатится на regex-чистку.
    return null;
  } finally {
    clearTimeout(timeout);
  }
}
