// Опциональная замена cleanTicketDescription (см. lib/textClean.ts) на
// переписывание через Groq — включается тоглом aiCleaningEnabled (см.
// lib/settings.ts). В отличие от регулярок ИИ понимает контекст, а не
// просто вырезает паттерны, поэтому лучше держит смысл сообщения. Groq
// выбран вместо Gemini из-за бесплатного tier без привязки карты (у
// Gemini free-tier квота равна 0, пока не подключишь биллинг).
//
// Вызывается из вебхука Telegram, который должен ответить быстро — при
// любой ошибке/таймауте/отсутствии ключа возвращаем null, и вызывающий код
// молча откатывается на cleanTicketDescription, а не роняет обработку
// сообщения.
const GROQ_MODEL = process.env.GROQ_MODEL || "llama-3.3-70b-versatile";

// Groq free tier: 100k токенов/день, лимит висит на аккаунте целиком (не на
// ключе) — второй ключ того же аккаунта квоту не обходит, нужен ключ с
// другого аккаунта. GROQ_API_KEY можно задать как один ключ или как
// несколько через запятую ("key1,key2") — при исчерпании/ошибке первого
// автоматически пробуем следующий, ничего в вызывающем коде менять не
// нужно.
function groqApiKeys(): string[] {
  return (process.env.GROQ_API_KEY ?? "")
    .split(",")
    .map((key) => key.trim())
    .filter(Boolean);
}

// Общий вызов Groq chat completions с перебором ключей — 429 (квота
// исчерпана) и любая другая ошибка/таймаут одного ключа переходят к
// следующему, а не сразу к null. Возвращает null, только если так
// ответили (или упали) вообще все ключи — вызывающий код как и раньше
// откатывается на regex-чистку/пропуск фичи.
async function callGroqChat(
  body: Record<string, unknown>,
  timeoutMs: number
): Promise<unknown> {
  for (const apiKey of groqApiKeys()) {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), timeoutMs);
    try {
      const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${apiKey}`,
        },
        signal: controller.signal,
        body: JSON.stringify(body),
      });
      if (res.ok) return await res.json();
    } catch {
      // Сеть/таймаут — пробуем следующий ключ.
    } finally {
      clearTimeout(timeout);
    }
  }
  return null;
}

const GROQ_TIMEOUT_MS = 8000;

// Ответ модели, означающий "в сообщении нет запроса, тикет заводить не
// нужно" (см. хвост SYSTEM_PROMPT). Отдельное слово, а не пустая строка:
// пустой ответ неотличим от сбоя, а сбой должен приводить к откату на
// regex-чистку, а не к молчаливой потере сообщения.
export const AI_SKIP = "SKIP";

export function isAiSkip(text: string): boolean {
  return text.trim().replace(/[.!]*$/, "").toUpperCase() === AI_SKIP;
}

